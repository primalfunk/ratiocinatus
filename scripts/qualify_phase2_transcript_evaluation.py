"""Qualify strict transcript evaluation on controlled public references."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from qualify_phase2_subtitles import qualify as qualify_subtitles
from ratiocinatus.addressing_contracts import MediaInterval, TimeDomain
from ratiocinatus.corpus_contracts import AudiovisualCorpus
from ratiocinatus.correction_contracts import TranscriptViewKind
from ratiocinatus.evaluation_contracts import (
    EvaluationAvailability,
    EvaluationStratum,
    ReferenceTranscript,
    ReferenceTranscriptSegment,
)
from ratiocinatus.kernel import canonical_bytes, load_contract, typed_id
from ratiocinatus.media import sha256_file
from ratiocinatus.transcript_contracts import TranscriptAssembly
from ratiocinatus.transcript_evaluation import evaluate_transcript

LINE_IDS = ("L001", "L002", "L003", "L004", "L005")


def _corpus_root(root: Path, variant: str) -> Path:
    values = list(
        (root / "phase1" / variant / "ingestions").glob("*/corpus")
    )
    if len(values) != 1:
        raise RuntimeError(
            f"expected one {variant} corpus, found {len(values)}"
        )
    return values[0]


def _reference(
    *,
    root: Path,
    fixture_root: Path,
    variant: str,
    assembly: TranscriptAssembly,
) -> ReferenceTranscript:
    corpus_root = _corpus_root(root, variant)
    corpus = load_contract(
        (corpus_root / "manifest.json").read_bytes(), AudiovisualCorpus
    )
    definitions_path = fixture_root / "script" / "line_definitions.json"
    schedule_path = (
        fixture_root / "schedules" / variant / "line_schedule.json"
    )
    definitions = json.loads(
        definitions_path.read_text(encoding="utf-8-sig")
    )
    schedule = json.loads(
        schedule_path.read_text(encoding="utf-8-sig")
    )
    definition_by_id = {
        item["line_id"]: item["text"] for item in definitions["lines"]
    }
    schedule_by_id = {
        item["line_id"]: item for item in schedule["lines"]
    }
    stratum = (
        EvaluationStratum.CLEAN_SPEECH
        if variant == "clean"
        else EvaluationStratum.OTHER_CONTROLLED
    )
    segments = []
    for line_id in LINE_IDS:
        item = schedule_by_id[line_id]
        start = item["start_microseconds"]
        duration = item["duration_microseconds"]
        normalized = MediaInterval(
            domain=TimeDomain.NORMALIZED_CORPUS,
            start_microseconds=start,
            duration_microseconds=duration,
        )
        source = MediaInterval(
            domain=TimeDomain.SOURCE_MEDIA,
            start_microseconds=(
                start + assembly.source_mapping_offset_microseconds
            ),
            duration_microseconds=duration,
        )
        segments.append(
            ReferenceTranscriptSegment(
                reference_segment_id=f"public-line:{line_id}",
                source_interval=source,
                normalized_audio_interval=normalized,
                text=definition_by_id[line_id],
                strata=(stratum,),
            )
        )
    normalized_audio = corpus_root / corpus.normalized_audio.relative_path
    definition_hash = sha256_file(definitions_path)
    schedule_hash = sha256_file(schedule_path)
    return ReferenceTranscript(
        reference_id=typed_id(
            "txreference",
            corpus.corpus_id,
            variant,
            LINE_IDS,
            definition_hash,
            schedule_hash,
        ),
        fixture_id=schedule["fixture_id"],
        variant=variant,
        corpus_id=corpus.corpus_id,
        source_id=corpus.source_id,
        source_sha256=corpus.source_fingerprint.digest,
        normalized_audio_sha256=sha256_file(normalized_audio),
        normalized_audio_duration_microseconds=(
            assembly.normalized_audio_duration_microseconds
        ),
        source_mapping_offset_microseconds=(
            assembly.source_mapping_offset_microseconds
        ),
        source_document_sha256=definition_hash,
        schedule_document_sha256=schedule_hash,
        provenance=(
            "Public project-authored line definitions and variant schedule "
            "prepared and frozen before transcription-provider selection."
        ),
        independence_statement=(
            "Reference text was not generated by the evaluated provider and "
            "was not supplied to speech detection or transcription inference."
        ),
        segments=tuple(segments),
    )


def qualify(root: Path, fixture_root: Path) -> dict[str, object]:
    subtitle_source = qualify_subtitles(root, fixture_root)
    results: list[dict[str, object]] = []
    for item in subtitle_source["results"]:
        variant = item["variant"]
        assembly_root = (
            root
            / "phase2"
            / variant
            / "transcript-assemblies"
            / item["base_assembly_id"]
        )
        revision_root = (
            root
            / "phase2"
            / variant
            / "transcript-revisions"
            / item["revision_id"]
        )
        subtitle_root = root / item["corrected_export_relative"]
        assembly = load_contract(
            (assembly_root / "assembly.json").read_bytes(),
            TranscriptAssembly,
        )
        reference = _reference(
            root=root,
            fixture_root=fixture_root,
            variant=variant,
            assembly=assembly,
        )
        reference_path = (
            root / "evaluation-references" / f"{variant}.json"
        )
        reference_path.parent.mkdir(parents=True, exist_ok=True)
        reference_path.write_bytes(canonical_bytes(reference))
        report, stored, first_reused = evaluate_transcript(
            assembly_root,
            reference_path,
            root / "phase2" / variant,
            revision_root=revision_root,
            view_kind=TranscriptViewKind.CURRENT_CORRECTED,

            subtitle_export_root=subtitle_root,
        )
        repeated = evaluate_transcript(
            assembly_root,
            reference_path,
            root / "phase2" / variant,
            revision_root=revision_root,
            view_kind=TranscriptViewKind.CURRENT_CORRECTED,

            subtitle_export_root=subtitle_root,
        )
        results.append(
            {
                "variant": variant,
                "evaluation_id": report.evaluation_id,
                "reference_id": reference.reference_id,
                "transcript_version_id": report.transcript_version_id,
                "view_kind": report.view_kind.value,
                "word_error_rate": report.aggregate.word_error_rate,
                "character_error_rate": (
                    report.aggregate.character_error_rate
                ),
                "word_substitutions": (
                    report.aggregate.word_substitution_count
                ),
                "word_deletions": report.aggregate.word_deletion_count,
                "word_insertions": report.aggregate.word_insertion_count,
                "segment_timing_available": (
                    report.segment_timing.availability
                    == EvaluationAvailability.AVAILABLE
                ),
                "mean_segment_start_error_microseconds": (
                    report.segment_timing.mean_start_error_microseconds
                ),
                "mean_segment_end_error_microseconds": (
                    report.segment_timing.mean_end_error_microseconds
                ),
                "word_timing_explicitly_unavailable": (
                    report.word_timing.availability
                    == EvaluationAvailability.UNAVAILABLE_REFERENCE
                ),
                "candidate_selection_explicitly_unavailable": (
                    report.candidate_selection.availability
                    == EvaluationAvailability.UNAVAILABLE_REFERENCE
                ),
                "confidence_reliability_available": (
                    report.confidence_reliability.availability
                    == EvaluationAvailability.AVAILABLE
                ),
                "reliability_bin_count": len(
                    report.confidence_reliability.bins
                ),
                "subtitle_valid": report.subtitle_cues.valid,
                "subtitle_cue_count": report.subtitle_cues.cue_count,
                "correction_impact_available": (
                    report.correction_impact.availability
                    == EvaluationAvailability.AVAILABLE
                ),
                "word_error_rate_change": (
                    report.correction_impact.word_error_rate_change
                ),
                "character_error_rate_change": (
                    report.correction_impact.character_error_rate_change
                ),
                "strata": [
                    value.stratum.value for value in report.strata
                ],
                "reviewed_reference_segment_count": (
                    report.reviewed_reference_segment_count
                ),
                "first_reused": first_reused,
                "second_reused": repeated[2],
                "stable_repeated_report": repeated[0] == report,
                "stored_relative": stored.relative_to(root).as_posix(),
            }
        )
    assertions = {
        "subtitle_qualification_passed": (
            subtitle_source["status"] == "passed"
        ),
        "all_views_and_versions_declared": all(
            item["view_kind"] == "current_corrected"
            and item["transcript_version_id"]
            for item in results
        ),
        "all_edit_metrics_available": all(
            item["word_error_rate"] is not None
            and item["character_error_rate"] is not None
            for item in results
        ),
        "all_segment_timing_available": all(
            item["segment_timing_available"] for item in results
        ),
        "all_unavailable_metrics_explicit": all(
            item["word_timing_explicitly_unavailable"]
            and item["candidate_selection_explicitly_unavailable"]
            for item in results
        ),
        "all_reliability_analyses_available": all(
            item["confidence_reliability_available"]
            and item["reliability_bin_count"] > 0
            for item in results
        ),
        "all_subtitle_exports_valid": all(
            item["subtitle_valid"] and item["subtitle_cue_count"] > 0
            for item in results
        ),
        "all_correction_impacts_available": all(
            item["correction_impact_available"]
            and item["word_error_rate_change"] <= 0
            and item["character_error_rate_change"] <= 0
            for item in results
        ),
        "all_strata_reported": all(item["strata"] for item in results),
        "all_reference_segments_review_addressed": all(
            item["reviewed_reference_segment_count"] == len(LINE_IDS)
            for item in results
        ),
        "all_second_runs_reused": all(
            item["second_reused"] for item in results
        ),
        "all_repeated_reports_stable": all(
            item["stable_repeated_report"] for item in results
        ),
    }
    return {
        "qualification": "phase-2-controlled-transcript-evaluation",
        "status": "passed" if all(assertions.values()) else "failed",
        "reference_policy": (
            "Public L001-L005 text and schedules were prepared before provider "
            "selection and were never supplied to inference."
        ),
        "results": results,
        "assertions": assertions,
        "limitations": [
            "These synthetic controlled-excerpt metrics do not establish "
            "general transcription quality.",
            "The evaluated excerpt has no independently authored word timing "
            "or expected alternative-candidate labels; those metrics remain "
            "explicitly unavailable.",
            "Clean and other-controlled strata are represented here. Noise, "
            "overlap, clipping, quiet speech, and long-boundary strata occur "
            "outside this excerpt and require later expanded transcription.",
            "Confidence reliability is descriptive and does not establish "
            "provider-score calibration.",
        ],
    }


def markdown(report: dict[str, object]) -> str:
    lines = [
        "# Phase 2 controlled transcript-evaluation qualification",
        "",
        f"Status: **{str(report['status']).upper()}**",
        "",
        "| Variant | WER | CER | Start error (µs) | Correction ΔWER | Cache |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for item in report["results"]:
        lines.append(
            f"| `{item['variant']}` | {item['word_error_rate']:.4f} | "
            f"{item['character_error_rate']:.4f} | "
            f"{item['mean_segment_start_error_microseconds']:.1f} | "
            f"{item['word_error_rate_change']:.4f} | "
            f"{'reused' if item['second_reused'] else 'miss'} |"
        )
    lines.extend(
        [
            "",
            "The strict reports preserve reference provenance and source "
            "mapping, aggregate and stratified edit metrics, segment timing, "
            "descriptive confidence reliability, subtitle validity, explicit "
            "unavailable metrics, and correction impact.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    parser.add_argument("fixture_root", type=Path)
    parser.add_argument("json_output", type=Path)
    parser.add_argument("markdown_output", type=Path)
    args = parser.parse_args()
    report = qualify(
        args.root.resolve(), args.fixture_root.resolve(strict=True)
    )
    args.json_output.parent.mkdir(parents=True, exist_ok=True)
    args.json_output.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    args.markdown_output.write_text(markdown(report), encoding="utf-8")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
